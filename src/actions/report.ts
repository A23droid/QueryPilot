/**
 * report.ts — `qp report <file>`
 *
 * Generates a Markdown summary of a query's execution plan, findings, and
 * (optionally) a cost comparison against a saved baseline.
 *
 * Intended for CI: the output can be posted as a GitHub PR comment when a
 * regression is detected.
 *
 * Example usage:
 *   qp report queries/report.sql > report.md
 *   # then post report.md as a PR comment
 */

import { readFile } from "node:fs/promises";
import { explainQuery } from "../db/explain.js";
import { formatPlanNode } from "../utils/planPrinter.js";
import { analyzePlan } from "../utils/planAnalyzer.js";
import { loadBaseline, diffCost } from "../utils/baseline.js";
import {
  diffCarbon,
  formatCarbonMarkdown,
  calculateCarbonMetrics,
} from "../utils/carbon.js";
import { pool } from "../db/connection.js";

/** Default threshold: cost increase above this % is flagged as a regression. */
const DEFAULT_REGRESSION_THRESHOLD_PCT = 20;

function severityIcon(severity: string): string {
  switch (severity) {
    case "critical":
      return "🔴 CRITICAL";
    case "warning":
      return "🟡 WARNING ";
    case "info":
      return "🔵 INFO    ";
    default:
      return "⚪ UNKNOWN ";
  }
}

function fmtMs(n: number | undefined): string {
  return n !== undefined ? n.toFixed(2) : "?";
}

/**
 * Build a Markdown report for a SQL file.
 * Returns the Markdown string (does not print to stdout).
 */
export async function generateReport(
  file: string,
  threshold = DEFAULT_REGRESSION_THRESHOLD_PCT,
): Promise<string> {
  const sql = await readFile(file, "utf8");
  const plan = await explainQuery(sql);
  const findings = analyzePlan(plan);

  const lines: string[] = [];

  // ── Header ────────────────────────────────────────────────────────────
  lines.push("# QueryPilot Report");
  lines.push("");
  lines.push(`**File:** \`${file}\``);
  lines.push(`**Generated:** ${new Date().toISOString()}`);
  lines.push("");

  // ── Execution Plan ────────────────────────────────────────────────────
  lines.push("## Execution Plan");
  lines.push("");
  lines.push("```text");
  lines.push(formatPlanNode(plan));
  lines.push("```");
  lines.push("");

  // ── Findings ──────────────────────────────────────────────────────────
  lines.push(`## Findings (${findings.length})`);
  lines.push("");

  if (findings.length === 0) {
    lines.push("✔ No performance issues detected.");
  } else {
    lines.push("| Severity | Message | Suggestion |");
    lines.push("|----------|---------|------------|");
    for (const f of findings) {
      const suggestion = f.suggestion.replace(/\n/g, " ").replace(/\|/g, "\\|");
      lines.push(
        `| ${severityIcon(f.severity)} | ${f.message.replace(/\|/g, "\\|")} | \`${suggestion}\` |`,
      );
    }
  }
  lines.push("");

  // ── Cost Comparison vs Baseline ───────────────────────────────────────
  const baseline = await loadBaseline(file);
  if (baseline) {
    const diff = diffCost(baseline, plan);
    const isRegression = diff.pctChange > threshold;
    const isImprovement = diff.pctChange < -threshold;

    lines.push("## Cost Comparison vs Baseline");
    lines.push("");
    lines.push("| | Cost |");
    lines.push("|---|------|");
    lines.push(`| Baseline (\`${baseline.capturedAt}\`) | ${diff.baseline.toFixed(2)} |`);
    lines.push(`| Current | ${diff.current.toFixed(2)} |`);
    const arrow = diff.delta > 0 ? "↑" : "↓";
    const status = isRegression
      ? "🔴 REGRESSION"
      : isImprovement
        ? "🟢 IMPROVEMENT"
        : "⚪ No significant change";
    lines.push(
      `| Change | ${arrow} ${Math.abs(diff.delta).toFixed(2)} (${
        diff.pctChange > 0 ? "+" : ""
      }${diff.pctChange.toFixed(1)}%) — ${status} |`,
    );
    lines.push("");

    if (isRegression && findings.length > 0) {
      lines.push("### Issues contributing to this regression:");
      for (const f of findings) {
        lines.push(
          `- ${severityIcon(f.severity)} ${f.message}`,
        );
      }
      lines.push("");
    }

    // ── Sustainability & Carbon Intensity (SCI) ──────────────────────────
    const carbonDiff = diffCarbon(diff.baseline, diff.current);
    lines.push(formatCarbonMarkdown(carbonDiff));
    lines.push("");
  } else {
    // Single plan carbon estimate
    const cost = Number(plan["Total Cost"] ?? 0);
    const metrics = calculateCarbonMetrics(cost);
    lines.push("### 🌱 Software Carbon Intensity (SCI) Estimate");
    lines.push(`> Quantified via Green Software Foundation SCI framework ($SCI = ((E \\times I) + M) / R$)`);
    lines.push("");
    lines.push(`- **Operational Energy:** \`${metrics.energyKwh} kWh\` per 10k executions`);
    lines.push(`- **Carbon Footprint:** \`${metrics.co2Grams} gCO₂e\` per 10k executions`);
    lines.push(`- **Est. Query CPU Time:** \`${metrics.estCpuMs} ms\``);
    lines.push("");
  }

  // ── Footer ────────────────────────────────────────────────────────────
  lines.push("---");
  lines.push("*Generated by QueryPilot*");
  lines.push("");

  await pool.end();
  return lines.join("\n");
}
